// ---- Front matter -------------------------------------------------------------------------------------------------------
// Supports `key: value`, `key: [a, b, c]`, and a list under a key (`facts:` then `  - Label: Value`).
function parseFrontMatter(raw, file) {
    const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
    if (!m) throw new Error(`${file}: missing front matter (--- ... --- at the top)`);
    const data = {};
    let key = null;
    for (const line of m[1].split(/\r?\n/)) {
        if (!line.trim() || line.trim().startsWith('#')) continue;
        const item = line.match(/^\s+-\s+(.*)$/);
        if (item && key) {
            if (!Array.isArray(data[key])) data[key] = [];
            data[key].push(item[1].trim());
            continue;
        }
        const kv = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
        if (!kv) throw new Error(`${file}: cannot read front matter line: ${line}`);
        key = kv[1];
        const v = kv[2].trim();
        if (v === '') data[key] = [];
        else if (v.startsWith('[') && v.endsWith(']')) data[key] = v.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean);
        else if (v === 'true' || v === 'false') data[key] = v === 'true';
        else data[key] = v.replace(/^(["'])(.*)\1$/, '$2');
    }
    return { data, body: m[2] };
}

// ---- Body: markdown -> blocks ---------------------------------------------------------------------------------------------
// Blocks are rendered by hand (not by marked's HTML output) so they get the site's own classes.
function mdBlocks(src, file) {
    const blocks = [];
    for (const t of marked.lexer(src)) {
        switch (t.type) {
            case 'space':
            case 'hr':
                break;
            case 'heading':
                if (t.depth === 2) blocks.push({ kind: 'h2', text: t.text.replace(/\s*\{-\}\s*$/, ''), plain: /\{-\}\s*$/.test(t.text) });
                else if (t.depth === 3) blocks.push({ kind: 'h3', html: inline(t.text) });
                else throw new Error(`${file}: use ## or ### for headings (the page title comes from the front matter)`);
                break;
            case 'paragraph': {
                const only = t.tokens.length === 1 ? t.tokens[0] : null;
                if (only?.type === 'image') blocks.push({ kind: 'figure', src: only.href, alt: only.text, caption: only.title });
                else blocks.push({ kind: 'p', html: inline(t.text) });
                break;
            }
            case 'list':
                blocks.push({ kind: 'list', items: t.items.map((i) => inline(i.text.trim())) });
                break;
            case 'blockquote':
                blocks.push({ kind: 'quote', html: t.tokens.filter((x) => x.type === 'paragraph').map((x) => inline(x.text)).join(' ') });
                break;
            case 'html':
                if (!t.raw.trim().startsWith('<!--')) blocks.push({ kind: 'html', raw: t.raw });
                break;
            default:
                throw new Error(`${file}: unsupported markdown (${t.type}). Use paragraphs, ## headings, lists, > quotes, images or ::: containers.`);
        }
    }
    return blocks;
}

// ::: containers - note (highlighted box), tip ("Try this"), steps (numbered cards)
function container(name, arg, inner, file) {
    const tokens = marked.lexer(inner).filter((t) => t.type !== 'space');
    if (name === 'note') {
        const parts = tokens.map((t) => {
            if (t.type !== 'paragraph') throw new Error(`${file}: a :::note can only contain paragraphs`);
            const only = t.tokens.length === 1 ? t.tokens[0] : null;
            return only?.type === 'link' ? { link: only.href, text: only.text } : { html: inline(t.text) };
        });
        return { kind: 'note', title: arg, parts };
    }
    if (name === 'tip') return { kind: 'tip', html: tokens.map((t) => inline(t.text)).join(' ') };
    if (name === 'steps') {
        const list = tokens.find((t) => t.type === 'list');
        if (!list) throw new Error(`${file}: :::steps needs a numbered list`);
        return {
            kind: 'steps',
            items: list.items.map((i) => {
                const m = i.text.trim().match(/^\*\*(.+?)\*\*[:.]?\s*([\s\S]*)$/);
                if (!m) throw new Error(`${file}: each step should look like "**Title**: description"`);
                return { title: esc(m[1]), html: inline(m[2]) };
            }),
        };
    }
    throw new Error(`${file}: unknown container :::${name}`);
}

function toBlocks(body, file) {
    const out = [];
    const lines = body.split(/\r?\n/);
    let buf = [];
    const flush = () => {
        if (buf.join('').trim()) out.push(...mdBlocks(buf.join('\n'), file));
        buf = [];
    };
    for (let i = 0; i < lines.length; i++) {
        const m = lines[i].match(/^:::(\w+)\s*(.*)$/);
        if (!m) {
            buf.push(lines[i]);
            continue;
        }
        flush();
        const inner = [];
        i++;
        while (i < lines.length && lines[i].trim() !== ':::') inner.push(lines[i++]);
        out.push(container(m[1], m[2].trim(), inner.join('\n'), file));
    }
    flush();
    return out;
}

// ---- Load posts -------------------------------------------------------------------------------------------------------------------
function loadPosts() {
    const posts = [];
    for (const name of fs.readdirSync(postsDir).filter((f) => f.endsWith('.md') && f.toLowerCase() !== 'readme.md')) {
        const file = `posts/${name}`;
        const { data, body } = parseFrontMatter(read(path.join(postsDir, name)), file);
        const slug = name.replace(/\.md$/, '');
        const hasPage = data.page !== false;
        for (const key of ['title', 'date']) if (!data[key]) throw new Error(`${file}: front matter needs "${key}"`);
        if (hasPage) for (const key of ['lead', 'category', 'gradient', 'icon']) if (!data[key]) throw new Error(`${file}: front matter needs "${key}"`);
        if (hasPage && !icons[data.icon]) throw new Error(`${file}: unknown icon "${data.icon}" (use one of: ${Object.keys(icons).join(', ')})`);

        const d = String(data.date).match(/^(\d{4})-(\d{2})(?:-(\d{2}))?$/);
        if (!d) throw new Error(`${file}: date should look like 2025-11-12 (or 2025-11)`);
        const month = MONTHS[Number(d[2]) - 1];
        const facts = (data.facts ?? []).map((f) => {
            const i = f.indexOf(': ');
            if (i < 0) throw new Error(`${file}: each fact should look like "Label: Value"`);
            return [f.slice(0, i), f.slice(i + 2)];
        });

        posts.push({
            slug,
            file,
            hasPage,
            title: data.title,
            sort: Number(d[1]) * 10000 + Number(d[2]) * 100 + Number(d[3] ?? 1),
            order: Number(data.order ?? 0),
            dateFull: d[3] ? `${month} ${Number(d[3])}, ${d[1]}` : `${month} ${d[1]}`,
            dateShort: `${month} ${d[1]}`,
            category: data.category ?? '',
            tags: data.tags ?? [],
            lead: data.lead ?? '',
            excerpt: data.excerpt ?? data.lead ?? '',
            gradient: data.gradient,
            icon: data.icon,
            image: data.image,
            toc: data.toc === true,
            numbered: data.numbered === true,
            searchHint: data.searchHint ?? data.excerpt ?? data.lead ?? '',
            keywords: data.keywords ?? `${data.title} ${(data.tags ?? []).join(' ')}`.toLowerCase(),
            facts,
            blocks: hasPage ? toBlocks(body, file) : [],
        });
    }
    posts.sort((a, b) => b.sort - a.sort || b.order - a.order || a.slug.localeCompare(b.slug));
    return posts;
}

