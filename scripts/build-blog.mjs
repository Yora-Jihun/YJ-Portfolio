// ---- Build ----------------------------------------------------------------------------------------------------------------------------
function build() {
    missingImages.length = 0;
    const posts = loadPosts();
    const pagePosts = posts.filter((p) => p.hasPage);
    const boundary = /(<\/header>)[\s\S]*?(<footer)/;

    // The shared header, footer and search dialog come from an existing inner page.
    const shell = read(path.join(root, 'skills.html'));
    if (!boundary.test(shell)) throw new Error('skills.html: cannot find the header/footer boundary');

    // 1. Article pages
    for (const post of pagePosts) {
        let html = shell.replace(/<title>[\s\S]*?<\/title>/, () => `<title>${esc(post.title)} | Yora Jihun</title>
    <meta name="description" content="${attr(post.excerpt)}">
    ${MARKER}${post.file} - edit that file, not this one -->`);
        html = html.replace(boundary, (_, a, b) => `${a}\n\n    ${pageMain(post, posts)}\n\n    ${b}`);
        fs.writeFileSync(path.join(root, `${post.slug}.html`), html.replace(/[ \t]+$/gm, ''));
    }

    // 2. Remove pages of posts that were deleted or turned into cards only
    const keep = new Set(pagePosts.map((p) => `${p.slug}.html`));
    for (const f of fs.readdirSync(root).filter((n) => n.endsWith('.html') && !keep.has(n))) {
        if (read(path.join(root, f)).includes(MARKER)) {
            fs.unlinkSync(path.join(root, f));
            console.log(`removed ${f} (no matching post in posts/)`);
        }
    }

    // 3. Blog list
    const blogPath = path.join(root, 'blog.html');
    const blog = read(blogPath);
    if (!boundary.test(blog)) throw new Error('blog.html: cannot find the header/footer boundary');
    fs.writeFileSync(blogPath, blog.replace(boundary, (_, a, b) => `${a}\n\n    ${blogMain(posts)}\n\n    ${b}`).replace(/[ \t]+$/gm, ''));

    // 4. Home page Guides
    const indexPath = path.join(root, 'index.html');
    const home = read(indexPath);
    const guides = /(<section id="guides"[\s\S]*?<ul class="mt-8 divide-y divide-border border-y border-border">\n)([\s\S]*?)(\n\s*<\/ul>)/;
    if (!guides.test(home)) throw new Error('index.html: cannot find the Guides list');
    fs.writeFileSync(indexPath, home.replace(guides, (_, a, __, c) => `${a}${guidesList(posts)}${c}`));

    // 5. Search
    const q = (s) => JSON.stringify(s).replace(/</g, '\\u003c');
    const entries = posts.map((p) => `    { group: 'Guide', title: ${q(p.title)}, hint: ${q(p.searchHint)}, href: ${q(p.hasPage ? `${p.slug}.html` : 'blog.html')}, keywords: ${q(p.keywords)} },`);
    fs.mkdirSync(path.join(root, 'src/generated'), { recursive: true });
    fs.writeFileSync(
        path.join(root, 'src/generated/posts-search.js'),
        `// Generated by scripts/build-blog.mjs from posts/*.md. Do not edit by hand.\nexport const postSearch = [\n${entries.join('\n')}\n];\n`,
    );

    console.log(`blog built: ${posts.length} posts (${pagePosts.length} articles), newest first: ${posts.slice(0, 3).map((p) => p.slug).join(', ')}...`);
    for (const src of new Set(missingImages)) console.log(`note: image not found yet, skipped: ${src}`);
}

if (process.argv.includes('--watch')) {
    const run = () => {
        try {
            build();
            // Nudge the CSS build so any new Tailwind classes in the generated pages get compiled.
            const now = new Date();
            fs.utimesSync(path.join(root, 'src/main.css'), now, now);
        } catch (error) {
            console.error(`\n${error.message}\n`);
        }
    };
    run();
    let timer;
    fs.watch(postsDir, () => {
        clearTimeout(timer);
        timer = setTimeout(run, 250);
    });
    console.log('watching posts/ for changes...');
} else {
    try {
        build();
    } catch (error) {
        console.error(`\n${error.message}\n`);
        process.exit(1);
    }
}
