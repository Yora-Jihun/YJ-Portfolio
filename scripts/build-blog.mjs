const missingImages = [];

function renderBlock(b) {
    switch (b.kind) {
        case 'p':
            return `<p class="mt-4 text-[17px] leading-8 text-ink/80 dark:text-white/80">${b.html}</p>`;
        case 'h3':
            return `<h3 class="mt-8 text-lg font-semibold text-ink dark:text-white">${b.html}</h3>`;
        case 'list':
            return `<ul class="mt-6 space-y-3 rounded-2xl bg-surface p-6 ring-1 ring-border">
${b.items.map((f) => `                    <li class="flex items-start gap-3 text-[15px] leading-relaxed text-ink dark:text-white">${check}<span>${f}</span></li>`).join('\n')}
                </ul>`;
        case 'quote':
            return `<blockquote class="mt-8 border-l-2 border-accent pl-5 text-xl leading-relaxed font-medium text-ink dark:text-white">${b.html}</blockquote>`;
        case 'figure': {
            if (!/^https?:/.test(b.src) && !fs.existsSync(path.join(root, b.src))) {
                missingImages.push(b.src);
                return '';
            }
            return `<figure class="mt-6 overflow-hidden rounded-2xl ring-1 ring-border">
                    <img src="${attr(b.src)}" alt="${attr(b.alt)}" loading="lazy" class="w-full object-cover">${b.caption ? `
                    <figcaption class="bg-surface px-4 py-3 text-xs text-muted">${esc(b.caption)}</figcaption>` : ''}
                </figure>`;
        }
        case 'html':
            return b.raw;
        case 'tip':
            return `<aside class="mt-6 flex gap-3 rounded-2xl bg-accent-soft p-4 text-[15px] leading-relaxed text-ink dark:text-white">
                    <svg class="mt-0.5 h-4 w-4 shrink-0 text-accent" viewBox="0 0 20 20" fill="none" aria-hidden="true">${icons.bolt}</svg>
                    <p><strong class="font-semibold">Try this.</strong> ${b.html}</p>
                </aside>`;
        case 'steps':
            return `<ol class="mt-6 grid gap-4 sm:grid-cols-3">
${b.items.map((s, i) => `                    <li class="rounded-2xl bg-white p-5 ring-1 ring-border dark:bg-white/5">
                        <span class="flex h-7 w-7 items-center justify-center rounded-full bg-accent text-xs font-semibold text-white">${i + 1}</span>
                        <h3 class="mt-3 font-semibold text-ink dark:text-white">${s.title}</h3>
                        <p class="mt-1 text-sm leading-relaxed text-muted">${s.html}</p>
                    </li>`).join('\n')}
                </ol>`;
        case 'note':
            return `<aside class="mt-12 rounded-2xl bg-accent-soft p-6">
                    <p class="font-semibold text-ink dark:text-white">${esc(b.title)}</p>${b.parts
                        .map((p) => (p.link
                            ? `\n                    <a href="${attr(p.link)}" class="mt-4 inline-flex items-center gap-1 text-sm font-medium text-accent transition-colors hover:text-accent-hover">${esc(p.text)} ${arrow}</a>`
                            : `\n                    <p class="mt-1 text-[15px] leading-relaxed text-ink/80 dark:text-white/80">${p.html}</p>`))
                        .join('')}
                </aside>`;
        default:
            throw new Error(`unknown block ${b.kind}`);
    }
}

const factsHtml = (facts) => `<dl class="grid grid-cols-2 gap-x-6 gap-y-5 rounded-2xl bg-surface p-6 ring-1 ring-border ${facts.length === 4 ? 'sm:grid-cols-4' : 'sm:grid-cols-3'}">
${facts.map(([k, v]) => `                    <div>
                        <dt class="text-xs text-muted">${esc(k)}</dt>
                        <dd class="mt-1 text-[15px] font-semibold text-ink dark:text-white">${esc(v)}</dd>
                    </div>`).join('\n')}
                </dl>`;

// Long posts: each ## heading becomes a section the sticky "In this article" list follows.
function sectionsOf(post) {
    const sections = [];
    const preface = [];
    let current = null;
    let n = 0;
    for (const b of post.blocks) {
        if (b.kind === 'h2') {
            current = { id: slugify(b.text), title: b.text, num: post.numbered && !b.plain ? ++n : 0, blocks: [] };
            sections.push(current);
        } else (current ? current.blocks : preface).push(b);
    }
    return { sections, preface };
}

const words = (post) =>
    [post.lead, ...post.facts.flat(), ...post.blocks.flatMap((b) => [b.text, b.html, b.title, ...(b.items ?? []).map((i) => (typeof i === 'string' ? i : `${i.title} ${i.html}`)), ...(b.parts ?? []).map((p) => p.html ?? '')])]
        .filter(Boolean).join(' ').replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;

function pageMain(post, all) {
    const minutes = Math.max(1, Math.round(words(post) / 200));
    const others = all.filter((p) => p.hasPage && p.slug !== post.slug).slice(0, 5);
    const keepReading = `<p class="mt-8 text-[11px] font-semibold tracking-wider text-ink uppercase dark:text-white">Keep reading</p>
                    <ul class="mt-3 space-y-3 text-sm">
${others.map((o) => `                        <li><a href="${o.slug}.html" class="text-muted transition-colors hover:text-accent">${esc(o.title)}</a></li>`).join('\n')}
                        <li><a href="blog.html" class="inline-flex items-center gap-1 text-accent transition-colors hover:text-accent-hover">All posts ${arrow}</a></li>
                    </ul>`;

    let content;
    let aside;
    if (post.toc) {
        const { sections, preface } = sectionsOf(post);
        content = preface.map(renderBlock).join('\n                ') + sections
            .map((s, i) => `
                <section id="${s.id}" data-doc-section data-title="${attr(s.title)}" class="scroll-mt-28 lg:scroll-mt-20${i === 0 && !preface.length ? '' : ' pt-12'}">
                    <h2 class="text-2xl font-semibold tracking-tight text-ink dark:text-white">${s.num ? `<span class="mr-3 font-mono text-sm font-semibold text-accent">${String(s.num).padStart(2, '0')}</span>` : ''}${esc(s.title)}</h2>
                    ${s.blocks.map(renderBlock).join('\n                    ')}
                </section>`).join('');
        aside = `<aside class="hidden lg:block">
                <div class="sticky top-[4.5rem] max-h-[calc(100vh-6rem)] overflow-y-auto pt-2 pr-2">
                    <p class="pb-3 text-[11px] font-semibold tracking-wider text-ink uppercase dark:text-white">In this article</p>
                    <ul>
${sections.map((s) => `                        <li>
                            <a href="#${s.id}" @click="select('${s.id}')" :aria-current="active === '${s.id}' ? 'true' : null"
                                :class="active === '${s.id}' ? 'font-medium text-accent' : 'text-muted hover:text-ink dark:hover:text-white'"
                                class="block border-l-2 py-1.5 pl-4 text-sm transition-colors focus-visible:outline-none focus-visible:text-accent"
                                :style="active === '${s.id}' ? 'border-color: var(--color-accent)' : 'border-color: transparent'">${esc(s.title)}</a>
                        </li>`).join('\n')}
                    </ul>
                    ${keepReading}
                </div>
            </aside>`;
    } else {
        content = post.blocks
            .map((b) => (b.kind === 'h2' ? `<h2 class="mt-12 text-2xl font-semibold tracking-tight text-ink dark:text-white">${esc(b.text)}</h2>` : renderBlock(b)))
            .join('\n                ');
        aside = `<aside class="mt-14 lg:mt-0">
                <div class="lg:sticky lg:top-[4.5rem]">
                    <p class="text-[11px] font-semibold tracking-wider text-ink uppercase dark:text-white">Tags</p>
                    <ul class="mt-3 flex flex-wrap gap-2">
                        ${tagChips(post.tags)}
                    </ul>

                    ${keepReading}
                </div>
            </aside>`;
    }

    return `<main${post.toc ? ' x-data="docsPage"' : ''} class="mx-auto w-full max-w-6xl px-4 pt-14 pb-24 sm:px-6 lg:px-8 lg:pt-20">
        <header class="max-w-3xl">
            <nav aria-label="Breadcrumb" class="flex items-center gap-2 text-xs text-muted">
                <a href="blog.html" class="transition-colors hover:text-ink dark:hover:text-white">Blog</a>
                <span aria-hidden="true">›</span>
                <span class="text-ink dark:text-white">${esc(post.title)}</span>
            </nav>

            <div class="mt-6 flex flex-wrap items-center gap-x-3 gap-y-2 text-xs">
                <span class="rounded-full bg-accent-soft px-2.5 py-1 font-semibold tracking-wide text-accent uppercase">${esc(post.category)}</span>
                <span class="text-muted">${post.dateFull}</span>
                <span class="text-muted" aria-hidden="true">·</span>
                <span class="text-muted">${minutes} min read</span>
            </div>

            <h1 class="mt-5 text-4xl font-semibold tracking-tight text-balance text-ink sm:text-6xl dark:text-white">${esc(post.title)}</h1>
            <p class="mt-5 text-xl leading-relaxed text-muted">${esc(post.lead)}</p>${post.toc && post.tags.length ? `
            <ul class="mt-6 flex flex-wrap gap-2">
                        ${tagChips(post.tags)}
            </ul>` : ''}

            <div class="mt-8 flex items-center gap-3">
                <img src="assets/images/about/portrait.jpg" alt="" width="80" height="104" class="h-10 w-10 rounded-full object-cover ring-1 ring-border">
                <div>
                    <p class="text-sm font-semibold text-ink dark:text-white">Yora Jihun</p>
                    <p class="text-xs text-muted">Lead System Engineer &amp; AI Specialist</p>
                </div>
            </div>
        </header>

        ${cover(post, 'mt-10 aspect-[21/9] rounded-3xl', 'h-16 w-16')}

        <div class="mt-14 lg:grid lg:grid-cols-[minmax(0,1fr)_15rem] lg:gap-16">
            <article class="max-w-2xl">
                ${post.facts.length ? factsHtml(post.facts) + '\n                ' : ''}${content}

                <a href="blog.html" class="mt-12 inline-flex items-center gap-1 text-sm font-medium text-accent transition-colors hover:text-accent-hover">← Back to all posts</a>
            </article>

            ${aside}
        </div>
    </main>`;
}

