// ---- Build ----------------------------------------------------------------------------------------------------------------------------
function build() {
    missingImages.length = 0;
    const { home, lessons } = load();
    const boundary = /(<\/header>)[\s\S]*?(<footer)/;
    const shell = read(path.join(root, 'skills.html'));
    if (!boundary.test(shell)) throw new Error('skills.html: cannot find the header/footer boundary');

    const write = (file, title, description, main, from) => {
        const html = shell
            .replace(/<title>[\s\S]*?<\/title>/, () => `<title>${esc(title)} | Yora Jihun</title>
    <meta name="description" content="${attr(description)}">
    ${MARKER}${from} - edit that file, not this one -->`)
            .replace(boundary, (_, a, b) => `${a}\n\n    ${main}\n\n    ${b}`);
        fs.writeFileSync(path.join(root, file), html.replace(/[ \t]+$/gm, ''));
    };

    write('docs.html', home.title, home.description, homeMain(home, lessons), home.file);
    for (const l of lessons) write(l.page, l.title, l.summary, lessonMain(l, lessons), l.file);

    // Remove pages of lessons that were deleted
    const keep = new Set(lessons.map((l) => l.page));
    for (const f of fs.readdirSync(root).filter((n) => /^lesson-.*\.html$/.test(n) && !keep.has(n))) {
        if (read(path.join(root, f)).includes(MARKER)) {
            fs.unlinkSync(path.join(root, f));
            console.log(`removed ${f} (no matching lesson in docs/)`);
        }
    }

    // Home page teaser
    const indexPath = path.join(root, 'index.html');
    const page = read(indexPath);
    const section = /<section id="docs"[\s\S]*?<\/section>/;
    if (!section.test(page)) throw new Error('index.html: cannot find the Docs section');
    fs.writeFileSync(indexPath, page.replace(section, () => teaser(lessons)));

    // Search
    const entries = lessons.map((l) => `    { group: 'Lesson', title: ${q(l.title)}, hint: ${q(l.searchHint)}, href: ${q(l.page)}, keywords: ${q(l.keywords)} },`);
    fs.mkdirSync(path.join(root, 'src/generated'), { recursive: true });
    fs.writeFileSync(
        path.join(root, 'src/generated/docs-search.js'),
        `// Generated by scripts/build-docs.mjs from docs/*.md. Do not edit by hand.\nexport const docsSearch = [\n${entries.join('\n')}\n];\n`,
    );

    console.log(`docs built: ${lessons.length} lessons (${lessons.map((l) => l.slug).join(', ')})`);
    for (const src of new Set(missingImages)) console.log(`note: image not found yet, skipped: ${src}`);
}

if (process.argv.includes('--watch')) {
    const run = () => {
        try {
            build();
            // Nudge the CSS build so any new Tailwind classes in the generated pages get compiled.
            const now = new Date();
            fs.utimesSync(path.join(root, 'src/main.css'), now, now);
        } catch (error) {
            console.error(`\n${error.message}\n`);
        }
    };
    run();
    let timer;
    fs.watch(docsDir, () => {
        clearTimeout(timer);
        timer = setTimeout(run, 250);
    });
    console.log('watching docs/ for changes...');
} else {
    try {
        build();
    } catch (error) {
        console.error(`\n${error.message}\n`);
        process.exit(1);
    }
}
